"""Generate rinux data tables from the C sources in ../linux.

Some kernel files are mostly data: errno numbers, CRC lookup tables, the
bit-reversal table and the int_log table, and some kernel tests carry
large vectors (SipHash test vectors, expected bitmap strings). Copying
them by hand invites typos, so this script lifts them straight out of the
C source and writes Rust files marked as generated. Test data goes to
lib/tests/data/, which the test files include!().

Run from anywhere, then format the generated sources:

    python rinux/scripts/gen_tables.py
    cd rinux && cargo fmt

The linux submodule must be checked out next to rinux/. The files under
lib/tests/data/ are include!()d, which rustfmt leaves alone.
"""

import re
import sys
from pathlib import Path

RINUX = Path(__file__).resolve().parent.parent
LINUX = RINUX.parent / "linux"
LIB_SRC = RINUX / "lib" / "src"
LIB_TEST_DATA = RINUX / "lib" / "tests" / "data"

HEADER = (
    "// SPDX-License-Identifier: {license}\n"
    "//\n"
    "// @generated by rinux/scripts/gen_tables.py from {sources}.\n"
    "// Do not edit by hand; re-run the script instead.\n\n"
)


def read(rel):
    path = LINUX / rel
    if not path.exists():
        sys.exit(f"missing {path}; is the linux submodule checked out?")
    return path.read_text(encoding="utf-8")


def c_array(rel, name):
    """Return the integer literals of `name[...] = { ... };` in a C file."""
    text = read(rel)
    m = re.search(r"\b" + re.escape(name) + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit(f"array {name} not found in {rel}")
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    return [int(tok, 0) for tok in re.findall(r"0[xX][0-9a-fA-F]+|\d+", body)]


def c_string(rel, name):
    """Return the value of `name[] ... = "..." "...";` in a C file, with its
    escapes kept as written. Comments are dropped first, so strings that
    contain "/*" are not supported."""
    text = re.sub(r"/\*.*?\*/", "", read(rel), flags=re.S)
    literal = r'"(?:[^"\\]|\\.)*"'
    m = re.search(r"\b" + re.escape(name) + r"\s*\[\s*\][^=]*=((?:\s*" + literal + r")+)\s*;",
                  text, re.S)
    if not m:
        sys.exit(f"string {name} not found in {rel}")
    return "".join(s[1:-1] for s in re.findall(literal, m.group(1)))


def rust_string(rust_name, value, doc, per_line=100):
    """A Rust &str static. C and Rust share the escapes used here (\\n)."""
    lines = [f"/// {doc}", f"pub static {rust_name}: &str = concat!("]
    i = 0
    while i < len(value):
        j = min(i + per_line, len(value))
        if value[j - 1] == "\\":  # don't split an escape
            j += 1
        lines.append(f'    "{value[i:j]}",')
        i = j
    lines.append(");\n")
    return "\n".join(lines)


def rust_array(rust_name, rust_type, values, width, per_line, doc):
    lines = [f"/// {doc}", f"pub static {rust_name}: [{rust_type}; {len(values)}] = ["]
    for i in range(0, len(values), per_line):
        chunk = values[i : i + per_line]
        lines.append("    " + " ".join(f"0x{v:0{width}x}," for v in chunk))
    lines.append("];\n")
    return "\n".join(lines)


def gen_errno():
    sources = [
        "include/uapi/asm-generic/errno-base.h",
        "include/uapi/asm-generic/errno.h",
        "include/linux/errno.h",
    ]
    define = re.compile(r"^#define\s+(E[A-Z0-9_]+)\s+(\w+)\s*(?:/\*\s*(.*?)\s*\*/)?\s*$")
    entries, aliases = [], []
    for rel in sources:
        for line in read(rel).splitlines():
            m = define.match(line)
            if not m:
                continue
            name, value, desc = m.group(1), m.group(2), (m.group(3) or "").rstrip(".")
            if value.isdigit():
                entries.append((name, int(value), desc))
            else:
                aliases.append((name, value))

    out = [HEADER.format(license="GPL-2.0 WITH Linux-syscall-note",
                         sources=", ".join(f"linux/{s}" for s in sources))]
    out.append("errno_table! {\n")
    for name, value, desc in entries:
        desc = desc.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    {name} = {value}, "{desc}";\n')
    out.append("}\n\n")
    for name, target in aliases:
        out.append(f"/// Alias of [`{target}`].\npub const {name}: Errno = {target};\n")
    (LIB_SRC / "errno_table.rs").write_text("".join(out), encoding="utf-8", newline="\n")


def gen_crc():
    specs = [
        ("lib/crc/crc16.c", "crc16_table", "CRC16_TABLE", "u16", 4, 8,
         "CRC-16 table, polynomial 0x8005 (bit-reversed 0xa001)."),
        ("lib/crc/crc-ccitt.c", "crc_ccitt_table", "CRC_CCITT_TABLE", "u16", 4, 8,
         "CRC-CCITT table, polynomial 0x1021 (bit-reversed 0x8408)."),
        ("lib/crc/crc-itu-t.c", "crc_itu_t_table", "CRC_ITU_T_TABLE", "u16", 4, 8,
         "CRC ITU-T V.41 table, polynomial 0x1021."),
        ("lib/crc/crc-t10dif-main.c", "t10_dif_crc_table", "T10_DIF_CRC_TABLE", "u16", 4, 8,
         "T10 DIF CRC16 table, polynomial 0x8bb7."),
        ("lib/crc/crc7.c", "crc7_be_syndrome_table", "CRC7_BE_SYNDROME_TABLE", "u8", 2, 8,
         "CRC-7 table (x^7 + x^3 + 1), left-aligned in each byte."),
        ("lib/crc/crc4.c", "crc4_tab", "CRC4_TAB", "u8", 1, 8,
         "CRC-4 table, polynomial 0b10111."),
    ]
    out = [HEADER.format(license="GPL-2.0-only",
                         sources=", ".join(f"linux/{s[0]}" for s in specs))]
    for rel, cname, rname, rtype, width, per_line, doc in specs:
        out.append(rust_array(rname, rtype, c_array(rel, cname), width, per_line, doc))
        out.append("\n")
    (LIB_SRC / "crc" / "tables.rs").write_text("".join(out).rstrip() + "\n",
                                                encoding="utf-8", newline="\n")


def gen_single(rel, cname, rname, rtype, width, per_line, doc, dest, license):
    out = HEADER.format(license=license, sources=f"linux/{rel}")
    out += rust_array(rname, rtype, c_array(rel, cname), width, per_line, doc)
    dest.write_text(out, encoding="utf-8", newline="\n")


def gen_test_data():
    LIB_TEST_DATA.mkdir(exist_ok=True)

    rel = "lib/tests/siphash_kunit.c"
    out = HEADER.format(license="(GPL-2.0-only OR BSD-3-Clause)", sources=f"linux/{rel}")
    out += rust_array("TEST_VECTORS_SIPHASH", "u64", c_array(rel, "test_vectors_siphash"), 16, 3,
                      "SipHash-2-4 of the bytes 0, 1, ..., i-1, for i in 0..64.")
    out += "\n"
    # The first definition is the BITS_PER_LONG == 64 one, which rinux uses.
    out += rust_array("TEST_VECTORS_HSIPHASH", "u32", c_array(rel, "test_vectors_hsiphash"), 8, 6,
                      "HalfSipHash (SipHash-1-3 on 64-bit machines) of the same inputs.")
    (LIB_TEST_DATA / "siphash_vectors.rs").write_text(out, encoding="utf-8", newline="\n")

    rel = "lib/test_bitmap.c"
    out = HEADER.format(license="GPL-2.0-only", sources=f"linux/{rel}")
    out += rust_string("LARGE_MASK", c_string(rel, "large_mask"),
                       "`%*pb` of `large_bitmap`, with a trailing newline.")
    out += "\n"
    out += rust_string("LARGE_LIST", c_string(rel, "large_list"),
                       "`%*pbl` of `large_bitmap` (more than 4 KiB), with a trailing newline.")
    (LIB_TEST_DATA / "test_bitmap_strings.rs").write_text(out, encoding="utf-8", newline="\n")


def main():
    gen_errno()
    gen_crc()
    gen_single("lib/bitrev.c", "byte_rev_table", "BYTE_REV_TABLE", "u8", 2, 8,
               "Each byte with its bit order reversed.", LIB_SRC / "bitrev_table.rs",
               "GPL-2.0-only")
    gen_single("lib/math/int_log.c", "logtable", "LOGTABLE", "u16", 4, 8,
               "log2(1 + i/256) * 2^16 for i in 0..256.", LIB_SRC / "math" / "int_log_table.rs",
               "LGPL-2.1-or-later")
    gen_test_data()
    print("tables written under", LIB_SRC, "and", LIB_TEST_DATA)


if __name__ == "__main__":
    main()
