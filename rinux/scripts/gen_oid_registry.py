"""Generate lib/src/oid_registry_data.rs from the Linux OID enum.

Linux builds lib/oid_registry_data.c from include/linux/oid_registry.h with
build_OID_registry.pl. This script does the same job for the Rust port:
it encodes each dotted OID in the header as ASN.1 content octets, computes
the hash look_up_OID() uses, and sorts the search table in the order the
binary search needs (hash, then length, then bytes compared from the end).

Usage: python3 scripts/gen_oid_registry.py [linux/include/linux/oid_registry.h]
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RINUX = HERE.parent
DEFAULT_HDR = RINUX.parent / "linux" / "include" / "linux" / "oid_registry.h"
OUT = RINUX / "lib" / "src" / "oid_registry_data.rs"


def encode(dotted: str) -> bytes:
    arcs = [int(a) for a in dotted.split(".")]
    assert len(arcs) >= 2, dotted
    out = bytearray([40 * arcs[0] + arcs[1]])
    for arc in arcs[2:]:
        groups = [arc & 0x7F]
        arc >>= 7
        while arc:
            groups.append((arc & 0x7F) | 0x80)
            arc >>= 7
        out.extend(reversed(groups))
    return bytes(out)


def hash_of(data: bytes) -> int:
    # look_up_OID(): hash = datasize - 1 + sum(octets * 33), folded to 8 bits.
    h = (len(data) - 1) & 0xFFFFFFFF
    for b in data:
        h = (h + b * 33) & 0xFFFFFFFF
    h = ((h >> 24) ^ (h >> 16) ^ (h >> 8) ^ h) & 0xFF
    return h


def main() -> None:
    hdr = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_HDR
    text = hdr.read_text(encoding="utf-8")
    body = text.split("enum OID {", 1)[1].split("OID__NR", 1)[0]
    entries = re.findall(r"^\s*(OID_\w+),\s*/\*\s*([0-9.]+)\s*\*/", body, re.M)
    names = [n for n, _ in entries]
    dotted = [d for _, d in entries]
    assert len(entries) >= 100, len(entries)
    assert len(set(names)) == len(names)

    encoded = [encode(d) for d in dotted]
    index = [0]
    for e in encoded:
        index.append(index[-1] + len(e))
    data = b"".join(encoded)
    assert index[-1] < 0x10000

    order = sorted(
        range(len(entries)),
        key=lambda i: (hash_of(encoded[i]), len(encoded[i]), encoded[i][::-1]),
    )
    table = [(hash_of(encoded[i]), i) for i in order]

    lines = []
    lines.append("// SPDX-License-Identifier: GPL-2.0-or-later")
    lines.append("//! The OID registry data for `look_up_OID()`.")
    lines.append("//!")
    lines.append("//! Generated by `rinux/scripts/gen_oid_registry.py` from")
    lines.append("//! `include/linux/oid_registry.h`, as Linux's `build_OID_registry.pl`")
    lines.append("//! generates `lib/oid_registry_data.c`. Do not edit by hand.")
    lines.append("")
    lines.append("#![allow(non_camel_case_types)]")
    lines.append("")
    lines.append("/// `enum OID`: the OIDs the kernel knows by name. `OID__NR` is the")
    lines.append("/// \"not held here\" value.")
    lines.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    lines.append("#[repr(u16)]")
    lines.append("pub enum Oid {")
    for n in names:
        lines.append(f"    {n},")
    lines.append("    OID__NR,")
    lines.append("}")
    lines.append("")
    lines.append("/// Every `Oid` variant in table order, so `OID_VARIANTS[i]` is OID `i`.")
    lines.append(f"pub const OID_VARIANTS: [Oid; {len(names)}] = [")
    for n in names:
        lines.append(f"    Oid::{n},")
    lines.append("];")
    lines.append("")
    lines.append(f"/// Number of OIDs in the registry (`OID__NR`).")
    lines.append(f"pub const OID_NR: usize = {len(names)};")
    lines.append("")
    lines.append("/// Dotted form of each OID, indexed by `Oid as usize`.")
    lines.append(f"pub const OID_DOTTED: [&str; {len(names)}] = [")
    for d in dotted:
        lines.append(f'    "{d}",')
    lines.append("];")
    lines.append("")
    lines.append("/// `oid_search_table`: `(hash, oid)` pairs sorted for the binary search.")
    lines.append(f"pub const OID_SEARCH_TABLE: [(u8, u16); {len(table)}] = [")
    for h, i in table:
        lines.append(f"    (0x{h:02x}, {i}),")
    lines.append("];")
    lines.append("")
    lines.append("/// `oid_index`: `OID_DATA[OID_INDEX[i]..OID_INDEX[i + 1]]` is OID `i`.")
    lines.append(f"pub const OID_INDEX: [u16; {len(index)}] = [")
    for k in range(0, len(index), 12):
        lines.append("    " + ", ".join(str(x) for x in index[k:k + 12]) + ",")
    lines.append("];")
    lines.append("")
    lines.append("/// `oid_data`: the ASN.1 content octets of every OID, back to back.")
    lines.append(f"pub const OID_DATA: [u8; {len(data)}] = [")
    for k in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[k:k + 12]) + ",")
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(names)} OIDs, {len(data)} bytes -> {OUT}")


if __name__ == "__main__":
    main()
