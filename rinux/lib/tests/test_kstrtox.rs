// Not in the C test: error codes and kstrtobool().

#[test]
fn error_codes() {
    use rinux_lib::errno::{EINVAL, ERANGE};
    assert_eq!(kstrtoull("18446744073709551616", 10), Err(ERANGE));
    assert_eq!(kstrtoull("12a", 10), Err(EINVAL));
    assert_eq!(kstrtou8("256", 10), Err(ERANGE));
    assert_eq!(kstrtoint("-2147483649", 10), Err(ERANGE));
    assert_eq!(kstrtoint("0x7fffffff", 0), Ok(i32::MAX));
    assert_eq!(kstrtoint("-010", 0), Ok(-8));
    // Parsing stops at a NUL, like a C string.
    assert_eq!(kstrtouint(b"42\0garbage", 10), Ok(42));
}

#[test]
fn kstrtobool_values() {
    for s in [
        "1", "y", "Y", "yes", "t", "true", "e", "enable", "on", "ON", "oN",
    ] {
        assert_eq!(kstrtobool(s), Ok(true), "{s:?}");
    }
    for s in [
        "0", "n", "N", "no", "f", "false", "d", "disable", "off", "OFF", "oF",
    ] {
        assert_eq!(kstrtobool(s), Ok(false), "{s:?}");
    }
    for s in ["", "o", "ok", "2", "x", " 1"] {
        assert!(kstrtobool(s).is_err(), "{s:?}");
    }
}

