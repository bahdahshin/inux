use rinux_lib::kstrtox::*;

macro_rules! test_ok {
    ($name:ident, $f:ident, $table:ident) => {
        #[test]
        fn $name() {
            for &(s, base, expected) in $table {
                assert_eq!($f(s, base), Ok(expected), "str {s:?}, base {base}");
            }
        }
    };
}

macro_rules! test_fail {
    ($name:ident, $f:ident, $table:ident) => {
        #[test]
        fn $name() {
            for &(s, base) in $table {
                let rv = $f(s, base);
                assert!(
                    rv.is_err(),
                    "str {s:?}, base {base}: expected an error, got {rv:?}"
                );
            }
        }
    };
}

