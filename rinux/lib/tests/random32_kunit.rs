use rinux_lib::random32::{RndState, seed_min};

/// Seeds like the C test: a "super-duper" LCG chain.
fn prandom_state_test_seed(seed: u32) -> RndState {
    let lcg = |x: u32| x.wrapping_mul(69069);
    let s1 = seed_min(lcg(seed), 2);
    let s2 = seed_min(lcg(s1), 8);
    let s3 = seed_min(lcg(s2), 16);
    let s4 = seed_min(lcg(s3), 128);
    RndState { s1, s2, s3, s4 }
}

#[test]
fn prandom_seed_boundary() {
    for &(seed, result) in TEST1 {
        let mut state = prandom_state_test_seed(seed);
        state.warmup();
        assert_eq!(state.next_u32(), result, "seed {seed}");
    }
}

/// Test cases against taus113 from the GSL library.
#[test]
fn prandom_taus113() {
    for &(seed, iteration, result) in TEST2 {
        let mut state = prandom_state_test_seed(seed);
        state.warmup();
        for _ in 0..iteration - 1 {
            state.next_u32();
        }
        assert_eq!(
            state.next_u32(),
            result,
            "seed {seed}, iteration {iteration}"
        );
    }
}

#[test]
fn bytes_follow_words() {
    let mut a = RndState::new(42);
    let mut b = a;
    let mut buf = [0u8; 11];
    a.fill_bytes(&mut buf);
    let w0 = b.next_u32().to_ne_bytes();
    let w1 = b.next_u32().to_ne_bytes();
    let w2 = b.next_u32().to_le_bytes();
    assert_eq!(&buf[..4], &w0);
    assert_eq!(&buf[4..8], &w1);
    assert_eq!(&buf[8..], &w2[..3]);
}

