//! Bitfield helpers: pack a value into, or pull it out of, a masked field.
//!
//! Ported from `include/linux/bitfield.h`. A field is described by its mask
//! (a contiguous run of set bits); the shift is implied by the mask's lowest
//! set bit, so callers never spell it. `FIELD_PREP(REG_FIELD_C, c)` becomes
//! `field_prep(REG_FIELD_C, c)`.
//!
//! The C macros are checked at compile time: a zero or non-contiguous mask
//! is a build error (`__bad_mask()`), and so is a constant value that does
//! not fit (`__field_overflow()`). Here a bad mask panics, since it is a
//! contract violation at the call site, and an oversized value is masked
//! off exactly as the C does at run time; [`field_fit`] asks first.
//!
//! The typed `u8_encode_bits()` ... `u64_get_bits()` family is generated by
//! [`make_op!`] as in C. The `le*`/`be*` variants take and return the stored
//! (byte-swapped) representation, as the `__le16`/`__be16` types do.

/// `field_multiplier()`: the lowest set bit of `field`, which is what a
/// value is multiplied by to land in the field.
///
/// Panics if `field` is zero or not a contiguous run of set bits, where C
/// fails to build with "bad bitfield mask".
pub const fn field_multiplier(field: u64) -> u64 {
    let filled = field | field.wrapping_sub(1);
    if field == 0 || filled & filled.wrapping_add(1) != 0 {
        panic!("bad bitfield mask");
    }
    field & field.wrapping_neg()
}

/// `field_mask()`: the mask shifted down to bit 0, so the largest value the
/// field holds.
pub const fn field_mask(field: u64) -> u64 {
    field / field_multiplier(field)
}

/// An unsigned integer a bitfield mask and register can be.
pub trait Field: Copy {
    /// The signed type of the same width, for [`field_get_signed`].
    type Signed: Copy;
    /// Widen to `u64`.
    fn to_u64(self) -> u64;
    /// Narrow from `u64`; the value must fit.
    fn from_u64(v: u64) -> Self;
    /// Narrow from `u64` and reinterpret as signed.
    fn signed_from_u64(v: u64) -> Self::Signed;
    /// Bits in the type, `BITS_PER_TYPE()`.
    const BITS: u32;
}

macro_rules! impl_field {
    ($($t:ty => $s:ty),* $(,)?) => {$(
        impl Field for $t {
            type Signed = $s;
            #[inline]
            fn to_u64(self) -> u64 {
                self as u64
            }
            #[inline]
            fn from_u64(v: u64) -> Self {
                v as $t
            }
            #[inline]
            fn signed_from_u64(v: u64) -> $s {
                v as $t as $s
            }
            const BITS: u32 = <$t>::BITS;
        }
    )*};
}

impl_field!(u8 => i8, u16 => i16, u32 => i32, u64 => i64);

/// `__bf_shf()`: the shift of a field, its lowest set bit.
#[inline]
fn bf_shf(mask: u64) -> u32 {
    mask.trailing_zeros()
}

/// `FIELD_MAX()`: the largest value `mask` can hold.
#[inline]
pub fn field_max<T: Field>(mask: T) -> T {
    T::from_u64(field_mask(mask.to_u64()))
}

/// `FIELD_FIT()`: whether `val` fits in `mask`.
#[inline]
pub fn field_fit<T: Field>(mask: T, val: T) -> bool {
    let mask = mask.to_u64();
    field_multiplier(mask);
    (val.to_u64() << bf_shf(mask)) & !mask == 0
}

/// `FIELD_PREP()`: `val` shifted into place and masked, ready to OR into a
/// register.
#[inline]
pub fn field_prep<T: Field>(mask: T, val: T) -> T {
    let mask = mask.to_u64();
    field_multiplier(mask);
    T::from_u64((val.to_u64() << bf_shf(mask)) & mask)
}

/// `FIELD_GET()`: the field's value in `reg`, shifted down to bit 0.
#[inline]
pub fn field_get<T: Field>(mask: T, reg: T) -> T {
    let mask = mask.to_u64();
    field_multiplier(mask);
    T::from_u64((reg.to_u64() & mask) >> bf_shf(mask))
}

/// `FIELD_GET_SIGNED()`: the field's value in `reg`, sign-extended from its
/// top bit.
#[inline]
pub fn field_get_signed<T: Field>(mask: T, reg: T) -> T::Signed {
    let mask = mask.to_u64();
    field_multiplier(mask);
    let lead = mask.leading_zeros();
    let v = ((reg.to_u64() as i64) << lead) >> (lead + bf_shf(mask));
    T::signed_from_u64(v as u64)
}

/// `FIELD_MODIFY()`: replace the field in `reg` with `val`.
#[inline]
pub fn field_modify<T: Field>(mask: T, reg: &mut T, val: T) {
    let m = mask.to_u64();
    *reg = T::from_u64((reg.to_u64() & !m) | field_prep(mask, val).to_u64());
}

/// `____MAKE_OP()`: the `<type>_encode_bits()`, `<type>_replace_bits()`,
/// `<type>p_replace_bits()` and `<type>_get_bits()` functions for one
/// storage type, with `to` and `from` converting between the CPU value and
/// the stored representation.
macro_rules! make_op {
    ($base:ty, $enc:ident, $rep:ident, $prep:ident, $get:ident, $to:expr, $from:expr) => {
        /// `<type>_encode_bits()`: `v` placed in `field`, in stored form.
        #[inline]
        #[must_use]
        pub fn $enc(v: $base, field: $base) -> $base {
            let f = field as u64;
            $to((((v as u64) & field_mask(f)) * field_multiplier(f)) as $base)
        }

        /// `<type>_replace_bits()`: `old` with `field` replaced by `val`.
        #[inline]
        #[must_use]
        pub fn $rep(old: $base, val: $base, field: $base) -> $base {
            (old & !$to(field)) | $enc(val, field)
        }

        /// `<type>p_replace_bits()`: replace `field` in `*p` with `val`.
        #[inline]
        pub fn $prep(p: &mut $base, val: $base, field: $base) {
            *p = (*p & !$to(field)) | $enc(val, field);
        }

        /// `<type>_get_bits()`: the value of `field` in stored `v`.
        #[inline]
        #[must_use]
        pub fn $get(v: $base, field: $base) -> $base {
            let f = field as u64;
            ((($from(v) as u64) & f) / field_multiplier(f)) as $base
        }
    };
}

